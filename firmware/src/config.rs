//! Build-time configuration from `config.toml`, validated by `build.rs`.

use core::net::Ipv4Addr;

pub const WIFI_SSID: &str = env!("FLIPDOT_WIFI_SSID");
pub const WIFI_PASSWORD: &str = env!("FLIPDOT_WIFI_PASSWORD");
pub const TIMEZONE: &str = env!("FLIPDOT_TIMEZONE");
pub const NTP_SERVER: &str = env!("FLIPDOT_NTP_SERVER");
pub const WEATHER_LOCATION: &str = env!("FLIPDOT_WEATHER_LOCATION");

const IP: &str = env!("FLIPDOT_IP");
const PREFIX: &str = env!("FLIPDOT_PREFIX");
const GATEWAY: &str = env!("FLIPDOT_GATEWAY");
const DNS: &str = env!("FLIPDOT_DNS");

// build.rs has already validated these, so the parses cannot fail.

pub fn ip() -> Ipv4Addr {
    IP.parse().unwrap()
}

pub fn prefix_len() -> u8 {
    PREFIX.parse().unwrap()
}

pub fn gateway() -> Ipv4Addr {
    GATEWAY.parse().unwrap()
}

pub fn dns() -> Ipv4Addr {
    DNS.parse().unwrap()
}

// `pub const TZ: chrono_tz::Tz`, generated by build.rs from `[clock] timezone`.
include!(concat!(env!("OUT_DIR"), "/timezone.rs"));
